import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { characterType } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");

    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    const characterPrompts: Record<string, string> = {
      warrior: "Pixel art character in Pokémon FireRed style. A warrior with black spiky hair, purple armor, and a blue glowing sword. Circular gradient background purple to black. Front view, 2D sprite, 64x64 pixels, retro game aesthetic.",
      archer: "Pixel art character in Pokémon FireRed style. An archer with long purple hair, black outfit with lilac accents, holding a futuristic blue bow. Circular gradient background purple to blue. Front view, 2D sprite, 64x64 pixels, retro game aesthetic.",
      mage: "Pixel art character in Pokémon FireRed style. A mage with blue neon cape, magical staff with glowing crystal, magic effects around. Circular gradient background dark blue. Front view, 2D sprite, 64x64 pixels, retro game aesthetic.",
      ninja: "Pixel art character in Pokémon FireRed style. A ninja with purple mask, dual blue glowing blades, soft shadow behind. Circular gradient background violet. Front view, 2D sprite, 64x64 pixels, retro game aesthetic.",
    };

    const prompt = characterPrompts[characterType] || characterPrompts.warrior;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-pro-image-preview",
        messages: [
          {
            role: "user",
            content: prompt,
          },
        ],
        modalities: ["image", "text"],
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(
          JSON.stringify({ error: "Rate limit exceeded, please try again later." }),
          {
            status: 429,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
          }
        );
      }
      if (response.status === 402) {
        return new Response(
          JSON.stringify({ error: "Payment required, please add credits to your workspace." }),
          {
            status: 402,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
          }
        );
      }
      const errorText = await response.text();
      console.error("AI gateway error:", response.status, errorText);
      return new Response(JSON.stringify({ error: "AI gateway error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const data = await response.json();
    const imageUrl = data.choices?.[0]?.message?.images?.[0]?.image_url?.url;

    if (!imageUrl) {
      throw new Error("No image generated");
    }

    return new Response(
      JSON.stringify({ imageUrl }),
      {
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      }
    );
  } catch (error) {
    console.error("Error:", error);
    return new Response(
      JSON.stringify({ error: error instanceof Error ? error.message : "Unknown error" }),
      {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      }
    );
  }
});
